"""Turn Paperfold glyphs into grid cells for the folding-paper animation.

Every glyph is drawn on a grid where 1 unit = one paper square. This samples
each unit square of a glyph and writes it as a full square, a half-square
triangle (named by its filled corner pair) or nothing, to a TypeScript file.

    pip install shapely fonttools
    python tools/paperfold/cells.py src/sections/opening/fold/glyphCells.ts
"""
import json
import os
import sys

from shapely.geometry import Polygon, box

sys.path.insert(0, os.path.dirname(__file__))
from build import G, SB  # noqa: E402  (glyph shapes and side bearing)

# A half-square triangle is named by the corner its right angle sits in.
TRIANGLES = {
    "tl": [(0, 1), (0, 0), (1, 1)],
    "tr": [(1, 1), (0, 1), (1, 0)],
    "bl": [(0, 0), (1, 0), (0, 1)],
    "br": [(1, 0), (1, 1), (0, 0)],
}


def classify(shape, x, y):
    cell = box(x, y, x + 1, y + 1)
    area = shape.intersection(cell).area
    if area < 0.2:
        return None
    if area > 0.8:
        return "full"
    best, best_score = None, -1.0
    for name, pts in TRIANGLES.items():
        tri = Polygon([(x + px, y + py) for px, py in pts])
        score = shape.intersection(tri).area - shape.intersection(cell.difference(tri)).area
        if score > best_score:
            best, best_score = name, score
    return best


def glyph_cells(name):
    shape, width, _ = G[name]
    minx, miny, maxx, maxy = shape.bounds
    cells = []
    for y in range(int(miny // 1), int(-(-maxy // 1))):
        for x in range(int(minx // 1), int(-(-maxx // 1))):
            kind = classify(shape, x, y)
            if kind:
                cells.append([x, y, kind])
    return {"advance": width + 2 * SB, "cells": cells}


def main(out):
    letters = "abcdefghijklmnopqrstuvwxyz"
    data = {ch: glyph_cells(ch) for ch in letters}
    with open(out, "w") as f:
        f.write("// Generated by tools/paperfold/cells.py from the Paperfold font. Do not edit.\n")
        f.write("// x, y in grid units from the glyph origin (y up); shape names the filled part.\n")
        f.write("import type { GlyphCells } from './types';\n\n")
        f.write("export const GLYPH_CELLS: Record<string, GlyphCells> = ")
        f.write(json.dumps(data, separators=(",", ":")))
        f.write(";\n")
    print("wrote", out)


if __name__ == "__main__":
    main(sys.argv[1])
